#!/usr/bin/env python3
"""Refreshes the homepage blocks for the done-for-you agency and the
"Fresh from the research desk" grid (latest 6 Long View articles).
Re-run after publishing new articles:  python3 scripts/build-research-desk.py
"""
import html, os, re

ROOT = os.path.join(os.path.dirname(__file__), '..')
esc = lambda s: html.escape(s, quote=True)

arts = []
for d in os.listdir(os.path.join(ROOT, 'the-long-view')):
    p = os.path.join(ROOT, 'the-long-view', d, 'index.html')
    if not os.path.isfile(p): continue
    s = open(p, encoding='utf-8').read()
    g = lambda pat: (re.search(pat, s, re.S) or [None, ''])[1]
    t = html.unescape(g(r'<title>(.*?)</title>')).split(' | ')[0].strip()
    date = g(r'article:published_time" content="([^"]*)"') or g(r'"datePublished":\s*"([^"]*)"')
    sec = html.unescape(g(r'article:section" content="([^"]*)"')) or 'The Long View'
    arts.append({'slug': d, 'title': t, 'desc': html.unescape(g(r'<meta name="description" content="([^"]*)"')),
                 'date': date[:10], 'img': g(r'og:image" content="([^"]*)"'), 'sec': sec})
arts.sort(key=lambda a: (a['date'], a['slug']), reverse=True)
MONTHS = 'Jan Feb Mar Apr May Jun Jul Aug Sep Oct Nov Dec'.split()
fmt = lambda d: f'{MONTHS[int(d[5:7]) - 1]} {int(d[8:10])}, {d[:4]}' if len(d) == 10 else ''

cards = ''.join(
    f'<a class="rd-card" href="/the-long-view/{a["slug"]}"><img src="{esc(a["img"])}" alt="Cover image for the article: {esc(a["title"])}" loading="lazy" width="1200" height="630">'
    f'<div class="rd-body"><div class="rd-meta">{esc(a["sec"])} · {fmt(a["date"])}</div><h3>{esc(a["title"])}</h3><p>{esc(a["desc"])}</p></div></a>'
    for a in arts[:6])

BLOCK = f'''<!-- RESEARCH-DESK:START (generated by scripts/build-research-desk.py) -->
<style>
.rd-grid{{display:grid;grid-template-columns:repeat(auto-fit,minmax(min(100%,300px),1fr));gap:18px;margin-top:8px}}
.rd-card{{display:flex;flex-direction:column;background:var(--surface);border:1px solid var(--line);border-radius:16px;overflow:hidden;text-decoration:none;color:var(--text);transition:border-color .2s,transform .2s}}
.rd-card:hover{{border-color:var(--cyan);transform:translateY(-2px)}}
.rd-card img{{width:100%;height:auto;aspect-ratio:1200/630;object-fit:cover;display:block;border-bottom:1px solid var(--line)}}
.rd-body{{padding:18px 20px 22px}}.rd-meta{{font-family:var(--mono);font-size:11.5px;letter-spacing:.08em;text-transform:uppercase;color:var(--cyan);margin-bottom:8px}}
.rd-card h3{{font-family:var(--display);font-size:19px;line-height:1.3;margin-bottom:8px}}.rd-card p{{color:var(--muted);font-size:14.5px;line-height:1.55}}
.ag-band{{display:grid;grid-template-columns:minmax(0,1.3fr) minmax(0,1fr);gap:28px;align-items:center;background:linear-gradient(135deg,rgba(45,212,255,.08),rgba(255,180,84,.06));border:1px solid var(--line-bright);border-radius:20px;padding:34px}}
.ag-band ul{{list-style:none;display:grid;gap:10px}}.ag-band li{{display:flex;justify-content:space-between;gap:12px;border-bottom:1px solid var(--line);padding-bottom:9px;color:var(--muted)}}.ag-band li b{{color:var(--text);white-space:nowrap}}
@media(max-width:860px){{.ag-band{{grid-template-columns:minmax(0,1fr);padding:24px}}}}
</style>
<section id="agency-band"><div class="wrap"><div class="ag-band">
<div><div class="sec-label">Done-for-you AI agency</div><h2 class="sec-h">Don't have time to do it yourself? <span class="grad">We do the work.</span></h2>
<p class="sec-desc">Fixed prices, published online. Pick a package, pay, send a two-minute brief, and the work starts. Siamak sets the strategy and reviews every deliverable.</p>
<div class="ph-btns" style="margin-top:18px"><a href="/agency" class="btn btn-pri">See the packages &rarr;</a></div></div>
<ul><li>AI Visibility Launch <b>$2,500</b></li><li>AI Visibility Growth <b>$1,500/mo</b></li><li>AI-Ready Website <b>from $4,500</b></li><li>Done-For-You AI Agent <b>$3,500 + $1,000/mo</b></li><li>Content Engine <b>$1,200/mo</b></li></ul>
</div></div></section>
<section id="agent-studio-band"><div class="wrap"><div class="ag-band">
<div><div class="sec-label">New &middot; Agent Studio</div><h2 class="sec-h">Build your own <span class="grad">AI business agent.</span></h2>
<p class="sec-desc">Name it, give it jobs and a voice, connect Shopify, WordPress, Wix and the tools you already use. It handles customers, follow-up, money and marketing &mdash; and asks before it acts. Built on the same system Siamak runs for his own stores.</p>
<div class="ph-btns" style="margin-top:18px"><a href="https://agents.siamakconsulting.com" class="btn btn-pri">Build my agent free &rarr;</a><a href="/ai-agents" class="btn btn-ghost">How AI agents work</a></div></div>
<ul><li>Agent preview <b>Free</b></li><li>Full agent blueprint <b>$99</b></li><li>Live agent on our platform <b>$249/mo &middot; waitlist</b></li><li>Done for you <b>$3,500 + $1,000/mo</b></li><li>Doctors, lawyers &amp; financial advisors <b>from $5,000 + $1,500/mo</b></li></ul>
</div></div></section>
<section id="research-desk"><div class="wrap">
<div class="sec-head"><div class="sec-label">Fresh from the research desk</div><h2 class="sec-h">What we're learning about <span class="grad">AI search</span></h2>
<p class="sec-desc">New research, field notes and plain-English guides from The Long View. Written by Siamak Kalhor.</p></div>
<div class="rd-grid">{cards}</div>
<p style="margin-top:22px"><a href="/the-long-view" class="btn btn-ghost">All {len(arts)} articles &rarr;</a></p>
</div></section>
<!-- RESEARCH-DESK:END -->
'''

p = os.path.join(ROOT, 'index.html')
s = open(p, encoding='utf-8').read()
if '<!-- RESEARCH-DESK:START' in s:
    s = re.sub(r'<!-- RESEARCH-DESK:START.*?<!-- RESEARCH-DESK:END -->\n', lambda m: BLOCK, s, flags=re.S)
else:
    anchor = '<!-- KNOWLEDGE BASE -->'
    assert s.count(anchor) == 1
    s = s.replace(anchor, BLOCK + anchor, 1)
open(p, 'w', encoding='utf-8').write(s)
print('homepage updated with', [a['slug'] for a in arts[:6]])
